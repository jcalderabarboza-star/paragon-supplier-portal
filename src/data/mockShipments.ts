export interface ShipmentLineItem {
  materialCode: string;
  description: string;
  qty: number;
  uom: string;
}

export type ShipmentStatus =
  | 'Pending ASN'
  | 'ASN Received'
  | 'In Transit'
  | 'Arrived at Port'
  | 'Customs Clearance'
  | 'At Dock'
  | 'Unloading'
  | 'Delivered'
  | 'Delayed';

